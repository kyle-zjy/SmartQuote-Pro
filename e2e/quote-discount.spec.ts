import { test, expect, resetApp, startNewQuote, addOpening, acceptDialogs } from './helpers'

test.beforeEach(async ({ page }) => {
  acceptDialogs(page)
  await resetApp(page)
})

test('discounts final prices and colour charges before GST and persists the result in the list and PDF', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/quotes/new')
  await page.getByLabel('First Name', { exact: true }).fill('Discount')
  await page.getByLabel('Surname', { exact: true }).fill('customer')
  await page.getByLabel('Site address', { exact: true }).fill('1 Test Street')
  await page.getByLabel('Discount (%)', { exact: true }).fill('10')
  await page.getByLabel('Discount note', { exact: true }).fill('Pensioner discount')
  await page.getByRole('button', { name: 'Start quote', exact: true }).click()
  await addOpening(page, { quantity: 2 })
  await page.getByLabel('Product unit price', { exact: true }).fill('500')
  await page.getByLabel('Frame colour (default)').selectOption({ label: 'Deco Bush Cherry Decoral (extra)' })
  await page.getByLabel('Colour extra $', { exact: true }).fill('50')
  const totals = page.locator('.quote-workspace__totals')
  await expect(totals).toContainText('Before discount: $1,050.00')
  await expect(totals).toContainText('Discount (10%): −$105.00')
  await expect(totals).toContainText('Subtotal: $945.00')
  await expect(totals).toContainText('GST: $94.50')
  await expect(totals).toContainText('Total: $1,039.50')
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  await page.goto('/quotes')
  const card = page.locator('.saved-quote-card')
  await expect(card).toContainText('$1,039.50')
  await card.getByRole('button', { name: 'Open', exact: true }).click()
  await expect(page.getByLabel('Discount (%)', { exact: true })).toHaveValue('10')
  await expect(page.getByLabel('Discount note', { exact: true })).toHaveValue('Pensioner discount')
  await page.getByRole('button', { name: 'Preview Customer Quote', exact: true }).click()
  const preview = page.getByRole('dialog', { name: 'Preview quote', exact: true })
  await expect(preview).toContainText('Discount note: Pensioner discount')
  await expect(preview.locator('.quote-sheet-foot__totals')).toContainText('Discount (10%)')
  await expect(preview.locator('.quote-sheet-foot__totals')).toContainText('−$105.00')
  await expect(preview).toContainText('$519.75')
  await page.screenshot({ path: 'test-results/discount-preview.png', fullPage: true })
  const downloadPromise = page.waitForEvent('download')
  await preview.getByRole('button', { name: 'Download PDF', exact: true }).click()
  expect(await (await downloadPromise).failure()).toBeNull()
})

test('invalid discounts cannot be saved; 100%, 0% and no GST calculate correctly', async ({ page }) => {
  await startNewQuote(page)
  await addOpening(page)
  await page.getByLabel('Product unit price', { exact: true }).fill('100')
  const percent = page.getByLabel('Discount (%)', { exact: true })
  await percent.fill('10')
  for (const value of ['-1', '101']) {
    await percent.fill(value)
    await expect(page.getByRole('alert')).toContainText('Enter a discount percentage from 0 to 100')
    await expect(page.getByRole('button', { name: 'Save quote', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Issue quote', exact: true })).toBeDisabled()
    await expect(page.locator('.quote-workspace__total-line')).toHaveText('Total: $99.00')
  }
  await percent.fill('100')
  await expect(page.locator('.quote-workspace__total-line')).toHaveText('Total: $0.00')
  await expect(page.getByRole('button', { name: 'Save quote', exact: true })).toBeEnabled()
  await percent.fill('12.5')
  await page.getByLabel('Include GST (10%)').uncheck()
  await expect(page.locator('.quote-workspace__total-line')).toHaveText('Total: $87.50')
  await percent.fill('0')
  await expect(page.locator('.quote-workspace__total-line')).toHaveText('Total: $100.00')
  await expect(page.locator('.quote-workspace__totals')).not.toContainText('Discount (')
})

test('issued discounts stay frozen while revisions can change them', async ({ page }) => {
  await startNewQuote(page)
  await addOpening(page)
  await page.getByLabel('Product unit price', { exact: true }).fill('100')
  await page.getByLabel('Discount (%)', { exact: true }).fill('10')
  await page.getByLabel('Discount note', { exact: true }).fill('Defence discount')
  await page.getByRole('button', { name: 'Issue quote', exact: true }).click()
  await expect(page.getByText('Issued', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Discount (%)', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Discount note', { exact: true })).toBeDisabled()
  const issued = await page.evaluate(() => JSON.parse(localStorage.getItem('smartquote-pro:archive')!)[0].quote)
  expect(issued.issuedSnapshot.discount).toEqual({ percent: 10, note: 'Defence discount', amount: 10, subtotalBeforeDiscount: 100 })
  await page.getByRole('button', { name: 'Revise quote', exact: true }).click()
  await page.getByLabel('Discount (%)', { exact: true }).fill('20')
  await page.getByLabel('Discount note', { exact: true }).fill('Revised discount')
  await page.getByRole('button', { name: 'Update saved quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  const old = await page.evaluate(() => JSON.parse(localStorage.getItem('smartquote-pro:archive')!).find((r: { version: number }) => r.version === 1).quote)
  expect(old).toEqual(issued)
  await expect(page.locator('.quote-workspace__total-line')).toHaveText('Total: $88.00')
  await page.goto('/quotes')
  await page.getByRole('button', { name: 'Snapshot', exact: true }).last().click()
  await expect(page.getByRole('dialog')).toContainText('Discount (10%)')
  await expect(page.getByRole('dialog')).toContainText('Discount note: Defence discount')
})

test('a read-only tab cannot change the discount', async ({ page, context }) => {
  await startNewQuote(page)
  await page.getByLabel('Discount (%)', { exact: true }).fill('10')
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  const other = await context.newPage()
  await other.goto(page.url())
  await expect(other.getByText(/This tab is read-only to protect/)).toBeVisible()
  await expect(other.getByLabel('Discount (%)', { exact: true })).toBeDisabled()
  await expect(other.getByLabel('Discount note', { exact: true })).toBeDisabled()
})
