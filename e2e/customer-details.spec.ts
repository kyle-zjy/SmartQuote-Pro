import { expect, test } from './helpers'
import { acceptDialogs, addOpening, resetApp } from './helpers'

test.beforeEach(async ({ page }) => {
  await resetApp(page)
  await page.goto('/quotes/new')
  await page.getByLabel('First Name', { exact: true }).fill('Customer')
  await page.getByLabel('Surname', { exact: true }).fill('with two addresses')
  await page.getByLabel('Email addresses', { exact: true }).fill('customer@example.com,accounts@example.com')
  await page.getByLabel('Site address', { exact: true }).fill('1 Site Street')
})

test('same-address selection stays in sync after creation', async ({ page }) => {
  const same = page.getByLabel('Billing address is the same as site address')
  await expect(same).toBeChecked()
  await expect(page.getByLabel('Billing address', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Billing address', { exact: true })).toHaveValue('1 Site Street')
  await page.getByRole('button', { name: 'Start quote', exact: true }).click()
  await expect(page.getByLabel('Billing address is the same as site address')).toHaveCount(0)
  await expect(page.getByLabel('Quote date')).toHaveCount(0)
  await expect(page.getByLabel('Quote number')).toHaveCount(0)
  await expect(page.getByLabel('Customer', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Phone', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Email addresses', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Site address', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Billing address', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Payment', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Amount paid')).toHaveCount(0)
  await expect(page.getByLabel('Frame colour (default)')).toBeVisible()
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Quote settings' })).toBeVisible()
  await expect(page.getByLabel('Customer', { exact: true })).toHaveCount(0)
})

test('separate addresses and multiple emails survive saving after the details are hidden', async ({ page }) => {
  await page.getByLabel('Billing address is the same as site address').uncheck()
  await page.getByLabel('Billing address', { exact: true }).fill('9 Billing Road')
  await page.getByRole('button', { name: 'Start quote', exact: true }).click()
  await expect(page.getByLabel('Site address', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Billing address', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Billing address is the same as site address')).toHaveCount(0)
  await expect(page.getByLabel('Site address', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Billing address', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Email addresses', { exact: true })).toHaveCount(0)
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('smartquote-pro:quote')!))
  expect(saved.customer.address).toBe('9 Billing Road')
  expect(saved.customer.email).toBe('customer@example.com,accounts@example.com')
  expect(saved.shipTo.address).toBe('1 Site Street')
})

test('split names survive saving, reopening and editing, and appear in quote output', async ({ page }) => {
  test.setTimeout(60_000)
  acceptDialogs(page)
  await page.getByLabel('First Name', { exact: true }).fill(' Mary Ann ')
  await page.getByLabel('Surname', { exact: true }).fill(' van der Berg ')
  await page.getByLabel('Billing address is the same as site address').uncheck()
  await page.getByLabel('Billing address', { exact: true }).fill('9 Billing Road')
  await page.getByRole('button', { name: 'Start quote', exact: true }).click()
  await addOpening(page)
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  await page.goto('/quotes')
  await expect(page.locator('.saved-quote-card')).toContainText('Mary Ann van der Berg')
  await page.locator('.saved-quote-card').getByRole('button', { name: 'Open', exact: true }).click()
  await page.locator('summary').filter({ hasText: /^Customer name$/ }).click()
  await expect(page.getByLabel('First Name', { exact: true })).toHaveValue('Mary Ann')
  await expect(page.getByLabel('Surname', { exact: true })).toHaveValue('van der Berg')
  await page.getByLabel('Surname', { exact: true }).fill("O'Neill")
  await page.getByRole('button', { name: 'Update saved quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  await page.reload()
  await page.locator('summary').filter({ hasText: /^Customer name$/ }).click()
  await expect(page.getByLabel('Surname', { exact: true })).toHaveValue("O'Neill")
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('smartquote-pro:quote')!))
  expect(saved.customer).toMatchObject({ firstName: 'Mary Ann', surname: "O'Neill", name: "Mary Ann O'Neill", address: '9 Billing Road' })
  expect(saved.shipTo).toMatchObject({ firstName: 'Mary Ann', surname: "O'Neill", name: "Mary Ann O'Neill", address: '1 Site Street' })
  await page.getByRole('button', { name: 'Preview Customer Quote', exact: true }).click()
  const preview = page.getByRole('dialog', { name: 'Preview quote', exact: true })
  await expect(preview.locator('.quote-party').getByText("Mary Ann O'Neill", { exact: true })).toHaveCount(2)
  const downloadPromise = page.waitForEvent('download')
  await preview.getByRole('button', { name: 'Download PDF', exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toContain("Mary-Ann-O'Neill")
  expect(await download.failure()).toBeNull()
  await page.getByRole('button', { name: 'Issue quote', exact: true }).click()
  await expect(page.getByLabel('First Name', { exact: true })).toBeDisabled()
  await expect(page.getByLabel('Surname', { exact: true })).toBeDisabled()
})
