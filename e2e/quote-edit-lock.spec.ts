import { test, expect, acceptDialogs, resetApp, startNewQuote, addOpening } from './helpers'

test('a second tab is read-only until the editing tab closes, then loads the latest edits', async ({ page, context }) => {
  await resetApp(page)
  await startNewQuote(page)
  await addOpening(page)
  await page.getByLabel('Product unit price').fill('699')
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  const other = await context.newPage()
  await other.goto(page.url())
  await expect(other.getByText(/This tab is read-only to protect/)).toBeVisible()
  await expect(other.getByLabel('Product unit price')).toBeDisabled()
  await other.locator('summary').filter({ hasText: /^Customer name$/ }).click()
  await expect(other.getByLabel('First Name', { exact: true })).toBeDisabled()
  await expect(other.getByLabel('Surname', { exact: true })).toBeDisabled()
  await expect(other.getByRole('button', { name: 'Update saved quote' })).toBeDisabled()
  await page.close()
  await other.getByRole('button', { name: 'Edit in this tab' }).click()
  await expect(other.getByLabel('Product unit price')).toBeEnabled()
  await expect(other.getByLabel('Product unit price')).toHaveValue('699')
  await other.getByLabel('Product unit price').fill('700')
  await other.getByRole('button', { name: 'Update saved quote' }).click()
  await expect(other.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
})

test('different quotes save concurrently and each tab resumes its own draft after reload', async ({ page, context }) => {
  acceptDialogs(page)
  await resetApp(page)
  await startNewQuote(page)
  await addOpening(page)
  const firstURL = page.url()
  const other = await context.newPage()
  acceptDialogs(other)
  await other.goto('/quotes')
  await startNewQuote(other, { name: 'Second customer', address: '2 Other St', phone: '0400000002' })
  await addOpening(other)
  const secondURL = other.url()
  expect(secondURL).not.toBe(firstURL)
  await page.getByLabel('Product unit price').fill('501')
  await other.getByLabel('Product unit price').fill('602')
  await Promise.all([
    page.getByRole('button', { name: 'Save quote', exact: true }).click(),
    other.getByRole('button', { name: 'Save quote', exact: true }).click(),
  ])
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('smartquote-pro:archive') ?? '[]').length)).toBe(2)
  await page.reload()
  await other.reload()
  await expect(page).toHaveURL(firstURL)
  await expect(other).toHaveURL(secondURL)
  await expect(page.getByLabel('Product unit price')).toHaveValue('501')
  await expect(other.getByLabel('Product unit price')).toHaveValue('602')
})
