import { readFile } from 'node:fs/promises'
import { test, expect, resetApp, startNewQuote, addOpening } from './helpers'

test('a downloadable backup restores quotes, drafts, reviews and photos in a clean browser and skips duplicates', async ({ page, browser }) => {
  test.setTimeout(60_000)
  await resetApp(page)
  await startNewQuote(page)
  await addOpening(page)
  await page.getByLabel('Living Room room photos', { exact: true }).setInputFiles({ name: 'room.png', mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') })
  await expect(page.locator('.room-photo-thumb img')).toHaveAttribute('src', /^data:image/)
  await page.getByRole('button', { name: 'Submit for Office Review' }).click()
  await expect(page.getByText('Submitted for office review.', { exact: true })).toBeVisible()
  await page.goto('/quotes')
  await page.getByText('Backup, restore & local drafts', { exact: true }).click()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download quote backup', exact: true }).click()
  const file = await downloading
  const contents = await readFile((await file.path())!, 'utf8')
  const data = JSON.parse(contents)
  expect(data.archives).toHaveLength(1)
  expect(data.reviews).toHaveLength(1)
  expect(data).not.toHaveProperty('staff')
  const clean = await browser.newContext({ baseURL: new URL(page.url()).origin })
  try {
    await clean.addInitScript(() => localStorage.setItem('smartquote-pro:session', JSON.stringify({ staffId: 'admin', role: 'admin', signedInAt: '2026-10-21T00:00:00.000Z' })))
    const target = await clean.newPage()
    await target.goto('/quotes')
    await target.getByText('Backup, restore & local drafts', { exact: true }).click()
    const upload = async () => target.getByLabel('Quote backup file', { exact: true }).setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(contents) })
    await upload()
    await expect(target.getByRole('region', { name: 'Backup restore preview' })).toContainText('1 saved versions')
    await target.getByRole('button', { name: 'Restore missing quotes and drafts' }).click()
    await expect(target.getByText(/Restored 1 saved versions/)).toBeVisible()
    await expect(target.locator('.saved-quote-card')).toContainText('Ada Lovelace')
    const original = await target.evaluate(() => localStorage.getItem('smartquote-pro:archive'))
    await upload()
    await expect(target.getByRole('region', { name: 'Backup restore preview' })).toContainText('0 saved versions')
    await target.getByRole('button', { name: 'Restore missing quotes and drafts' }).click()
    await expect(target.getByText(/Restored 0 saved versions/)).toBeVisible()
    expect(await target.evaluate(() => localStorage.getItem('smartquote-pro:archive'))).toBe(original)
    await target.locator('.saved-quote-card').getByRole('button', { name: 'Open', exact: true }).click()
    await expect(target.locator('.room-photo-thumb img')).toHaveAttribute('src', /^data:image/)
    expect(await target.evaluate(() => JSON.parse(localStorage.getItem('smartquote-pro:reviews')!)[0].status)).toBe('pending')
  } finally { await clean.close() }
})

test('invalid backup files leave existing quotes untouched', async ({ page }) => {
  await resetApp(page)
  await startNewQuote(page)
  await addOpening(page)
  await page.getByRole('button', { name: 'Save quote', exact: true }).click()
  await expect(page.getByText('Saved on this browser. Open it later from Quotes.', { exact: true })).toBeVisible()
  await page.goto('/quotes')
  const before = await page.evaluate(() => localStorage.getItem('smartquote-pro:archive'))
  await page.getByText('Backup, restore & local drafts', { exact: true }).click()
  await page.getByLabel('Quote backup file', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
  await expect(page.getByText(/not valid JSON/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Restore missing quotes and drafts' })).toHaveCount(0)
  expect(await page.evaluate(() => localStorage.getItem('smartquote-pro:archive'))).toBe(before)
})
