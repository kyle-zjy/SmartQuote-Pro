import { test, expect, acceptDialogs, resetApp, startNewQuote, addOpening } from './helpers'

test('issued documents retain the original company, bank and terms while new revisions use current settings', async ({ page }) => {
  acceptDialogs(page)
  await resetApp(page)
  await startNewQuote(page)
  await addOpening(page)
  const url = page.url()
  await page.getByRole('button', { name: 'Issue quote', exact: true }).click()
  await expect(page.getByText('Issued', { exact: true })).toBeVisible()
  await page.goto('/admin')
  await page.getByLabel('Name', { exact: true }).fill('Updated company')
  await page.getByLabel('Account', { exact: true }).fill('999999')
  await page.getByLabel('Contract text').fill('Updated contract for new quotes only')
  await page.getByLabel('Validity (days)').fill('7')
  await page.getByRole('button', { name: 'Save settings' }).click()
  await page.goto(url)
  await page.getByRole('button', { name: 'Preview Customer Quote' }).click()
  const preview = page.getByRole('dialog', { name: 'Preview quote', exact: true })
  await expect(preview.getByAltText('Goldco Security Group Pty Ltd')).toBeVisible()
  await expect(preview.getByText(/ACC:\s*405216/)).toBeVisible()
  await expect(preview.getByText('This Quote Valid for 30 Days*')).toBeVisible()
  await expect(preview.getByText('Updated contract for new quotes only')).toHaveCount(0)
  await preview.getByRole('button', { name: 'Back', exact: true }).click()
  await page.getByRole('button', { name: 'Revise quote' }).click()
  await page.getByRole('button', { name: 'Preview Customer Quote' }).click()
  await expect(preview.getByAltText('Updated company')).toBeVisible()
  await expect(preview.getByText('Updated contract for new quotes only')).toBeVisible()
  await expect(preview.getByText('This Quote Valid for 7 Days*')).toBeVisible()
})
